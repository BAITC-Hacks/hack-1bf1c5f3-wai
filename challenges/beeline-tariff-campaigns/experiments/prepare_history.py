"""Build reproducible, derived history summaries without modifying source CSVs.

Run from the challenge directory with: python experiments/prepare_history.py
Repeated monthly ARPU keys are collapsed to their median after exact duplicate
rows are removed. Conflicting values and negative observations are retained
and counted for review; negative values are not used in transition ratios.
"""

from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUTPUT = ROOT / "experiments" / "prepared_history"


def main() -> None:
    OUTPUT.mkdir(exist_ok=True)

    changes = pd.read_csv(DATA / "change_tariff.csv")
    change_key = ["ID_NUMBER", "TIME_KEY", "tariff_plan_code_from", "tariff_plan_code_to"]
    changes_clean = changes.drop_duplicates().copy()
    changes_clean.to_csv(OUTPUT / "change_tariff_exact_deduplicated.csv", index=False)

    valid = changes_clean.loc[changes_clean["AVG_ARPU_PREV_3M"] >= 100].copy()
    valid["arpu_segment"] = pd.cut(
        valid["AVG_ARPU_PREV_3M"],
        bins=[-np.inf, 1000, 5000, np.inf],
        labels=["LOW", "MID", "HIGH"],
    )
    valid["lift_ratio"] = (
        (valid["AVG_ARPU_NEXT_3M"] - valid["AVG_ARPU_PREV_3M"])
        / valid["AVG_ARPU_PREV_3M"]
    ).clip(-1, 3)
    transitions = (
        valid.groupby(
            ["tariff_plan_code_from", "tariff_plan_code_to", "arpu_segment"],
            observed=True,
        )["lift_ratio"]
        .agg(mean_lift_ratio="mean", median_lift_ratio="median", support="size")
        .reset_index()
        .sort_values(["tariff_plan_code_from", "tariff_plan_code_to", "arpu_segment"])
    )
    transitions.to_csv(OUTPUT / "transition_summary.csv", index=False)

    monthly = pd.read_csv(DATA / "arpu_monthly.csv")
    monthly_key = ["ID_NUMBER", "TIME_KEY"]
    exact_dedup = monthly.drop_duplicates()
    monthly_summary = (
        exact_dedup.groupby(monthly_key, as_index=False)
        .agg(
            ARPU_1M=("ARPU_1M", "median"),
            source_rows=("ARPU_1M", "size"),
            distinct_values=("ARPU_1M", "nunique"),
            negative_values=("ARPU_1M", lambda values: int((values < 0).sum())),
        )
    )
    monthly_summary.to_csv(OUTPUT / "arpu_monthly_median_by_id_month.csv", index=False)

    key_counts = monthly.groupby(monthly_key, sort=False).size()
    repeated_key_groups = int((key_counts > 1).sum())
    repeated_key_excess = int((key_counts - 1).clip(lower=0).sum())
    duplicate_key_rows = int(monthly.duplicated(monthly_key, keep=False).sum())
    negative_monthly = int((monthly["ARPU_1M"] < 0).sum())
    negative_previous = int((changes["AVG_ARPU_PREV_3M"] < 0).sum())
    negative_next = int((changes["AVG_ARPU_NEXT_3M"] < 0).sum())
    report = [
        "# Prepared history data notes",
        "",
        "Generated by `python experiments/prepare_history.py`; source CSVs are unchanged.",
        "All figures describe synthetic challenge data.",
        "",
        f"- Tariff changes: {len(changes)} source rows, {len(changes_clean)} after exact-row deduplication; {len(changes) - len(changes_clean)} exact excess rows.",
        f"- Repeated event keys after exact-row deduplication: {int(changes_clean.duplicated(change_key, keep=False).sum())} rows participate in a repeated key.",
        f"- Transition summary: {len(transitions)} source-tariff/destination-tariff/documented-ARPU-band groups; support counts are included.",
        f"- Transition ratios exclude pre-change ARPU below 100, use documented bands (<1000, 1000–5000, >5000), and are clipped to [-1, 3] to match the agent prior calculation.",
        f"- Monthly ARPU: {len(monthly)} source rows, {len(exact_dedup)} after exact-row deduplication ({len(monthly) - len(exact_dedup)} exact excess rows). It has {repeated_key_groups} repeated ID-month keys with {repeated_key_excess} excess rows; {duplicate_key_rows} rows participate in those keys.",
        f"- The monthly derived table has {len(monthly_summary)} unique ID-month keys. Conflicting values are represented by their median after exact duplicates are removed; `source_rows` and `distinct_values` preserve an audit trail.",
        f"- Negative values retained for review: {negative_monthly} monthly ARPU rows, {negative_previous} pre-change ARPU rows, {negative_next} post-change ARPU rows.",
        "- The agent's historical prior uses exact-deduplicated change events; campaign decisions still depend on pilot observations.",
    ]
    (OUTPUT / "README.md").write_text("\n".join(report) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
